// Guard for the AI explainers (src/tradetools). Every AI tool goes through runGuarded():
//   1. kill switch    AI_TOOLS_KILL (env: "all" or a comma list) or Admin → the tool's kill switch;
//                     checked on every request, so switching it takes effect at once
//   2. prompt check   a request for a trade, a pick, a prediction or a promise is refused before any AI call
//   3. AI or rules    the AI explains facts the server computed; without an AI provider (or when account
//                     figures may not be shared with it) a rule-based explanation is used instead
//   4. output check   an answer that recommends a trade or a security, predicts a price or promises
//                     a result is replaced by a refusal; the facts and sources are still shown
//   5. log            tool, a keyed hash of the user, the redacted question and answer, the outcome,
//                     the model; never the holdings, balances or other account figures
// Every answer carries the AI label and disclaimer and the list of data sources.
import crypto from 'node:crypto';
import { run, all, now } from '../db.js';
import { siteGet, siteSet } from '../site.js';
import { redact } from '../aiaccess.js';

export const AI_TOOLS = { portfolio: 'Portfolio concentration explainer', indicator: 'Indicator explainer (educational)' };
export const DISCLAIMER = 'Generated by AI. Educational information only, not investment advice, and it may be wrong. Check the figures yourself. Investing involves risk, including the loss of the money you invest.';
// When the answer was written by the fixed rules (no AI provider, a refusal, or AI not allowed to see account data).
export const RULES_DISCLAIMER = 'Written from fixed rules, not by AI. Educational information only, not investment advice. Check the figures yourself. Investing involves risk, including the loss of the money you invest.';
export const REFUSAL = 'This tool explains data; it cannot tell you what to buy, sell or hold, predict prices, or promise results. You can ask what a figure means, how it is calculated, or what risk it shows.';

// ---------- kill switch ----------
export function killed(tool, env = process.env) {
  const e = String(env.AI_TOOLS_KILL || '').split(',').map(s => s.trim()).filter(Boolean);
  if (e.includes('all') || e.includes(tool)) return true;
  const s = siteGet('aiKill', {}) || {};
  return s.all === true || s[tool] === true;
}
export async function setKill(tool, on) {
  if (tool !== 'all' && !AI_TOOLS[tool]) throw Object.assign(new Error('Unknown AI tool'), { status: 400 });
  const s = { ...(siteGet('aiKill', {}) || {}), [tool]: !!on };
  await siteSet('aiKill', s);
  return killStates();
}
export const killStates = () => Object.fromEntries(['all', ...Object.keys(AI_TOOLS)].map(t => [t, killed(t)]));

// ---------- checks ----------
// Requests for a recommendation, a pick, a prediction, a promise or an allocation.
const ASK = [
  [/\b(what|which)\b[^?.!]{0,40}\b(should|could|would|do you think)\b[^?.!]{0,30}\b(i|we|me)\b[^?.!]{0,30}\b(buy|sell|short|hold|invest|own|trade|get)\b/i, 'asks what to trade'],
  [/\bshould\s+(i|we)\b[^?.!]{0,40}\b(buy|sell|short|hold|invest|exit|close|add|trim|dump|keep|get (in|into|out))\b/i, 'asks whether to trade'],
  [/\b(what|which)\b[^?.!]{0,20}\b(stocks?|shares?|cryptos?|coins?|options?|etfs?|funds?|tickers?)\b[^?.!]{0,30}\b(buy|sell|short|invest|pick|own|get)\b/i, 'asks for a pick'],
  [/\b(recommend|suggest|pick|tip|name)\b[^?.!]{0,30}\b(stocks?|shares?|cryptos?|coins?|options?|etfs?|funds?|trades?|tickers?|calls?|puts?|investments?)\b/i, 'asks for a recommendation'],
  [/\b(best|top|hottest|safest)\b[^?.!]{0,30}\b(stocks?|shares?|cryptos?|coins?|options?|etfs?|funds?|trades?|investments?|calls|puts|plays)\b/i, 'asks for the best pick'],
  [/\b(buy|sell|short)\b[^?.!]{0,15}\b(now|today|tomorrow|this week|right now)\b/i, 'asks about trading now'],
  [/\b(is|are)\b[^?.!]{0,30}\b(a )?(good|great|bad|smart) (buy|sell|investment|trade|time to (buy|sell))\b/i, 'asks for a verdict'],
  [/\bwill\b[^?.!]{0,40}\b(go up|go down|rise|fall|drop|crash|moon|double|recover|rally|hit)\b/i, 'asks for a prediction'],
  [/\b(price target|target price|where will .{0,20} (be|trade)|how high|how low)\b/i, 'asks for a price prediction'],
  [/\b(guarantee|guaranteed|risk[- ]?free|sure thing|can'?t lose|safe bet|easy money)\b/i, 'asks for a promise'],
  [/\bhow much\b[^?.!]{0,30}\b(should|to)\b[^?.!]{0,20}\b(invest|put|buy|allocate|bet)\b/i, 'asks for an allocation'],
  [/\b(give|tell|send|show) (me )?(a |some |your )?(\w+ ){0,2}(trade|pick|tip|signal|play|buy|call|put)s?\b/i, 'asks for a trade'],
  [/\bwhat would you (buy|sell|short|pick|invest in|do with)|\bif you were (me|in my (shoes|position))\b/i, 'asks what the AI would trade'],
  [/\b(all[- ]in|yolo|max leverage)\b/i, 'asks about an all-in bet'],
  [/\bignore (all |your )?(previous|prior|above) (instructions|rules)|\bpretend (you are|to be)|\bjailbreak|\bdeveloper mode\b/i, 'tries to switch the rules off'],
];
// Answers that recommend, predict or promise. Tickers are matched only in capitals, so plain words
// ("sell-offs", "buyers") are not caught; educational descriptions ("traders call this overbought") pass.
const SAY = [
  [/\byou\s+(should|ought to|need to|must|might want to|may want to|could consider)\b[^.!?\n]{0,60}\b(buy|sell|short|hold|invest|add|trim|exit|close|reduce|increase|rebalance|diversify|move|switch)\b/i, 'tells the user what to do'],
  [/\b(i|we)\s+(would\s+)?(strongly\s+)?(recommend|suggest|advise|would buy|would sell|would avoid)\b/i, 'gives a recommendation'],
  [/\b(consider|try)\s+(buying|selling|shorting|adding|trimming|exiting|reducing|increasing)\b/i, 'suggests a trade'],
  [/\b(?:[Bb]uy|[Ss]ell|[Ss]hort|[Aa]ccumulate|[Gg]o long|[Gg]o short|[Ll]oad up on)\s+(some\s+|more\s+|shares of\s+|the\s+)?\$?[A-Z]{1,5}\b(?![a-z])/, 'names a security to trade'],
  [/^\s*(buy|sell|short)\b/im, 'tells the user to trade'],
  [/\b(strong\s+)?(buy|sell|hold)\s+(rating|signal|recommendation|call)\b/i, 'gives a rating'],
  [/\b(now is|this is|it'?s)\s+(a\s+)?(good|great|the right|the best)\s+(time|moment|opportunity)\s+to\b/i, 'times the market'],
  [/\b(will|(is|are) (going|likely|expected) to|should)\s+(likely\s+)?(rise|fall|go up|go down|rally|drop|double|crash|recover|outperform|underperform|hit)\b/i, 'predicts a price move'],
  [/\b(price target|target price)\b/i, 'gives a price target'],
  [/\b(guarantee[ds]?|risk[- ]free|can'?t lose|sure thing|safe bet|easy money|no risk)\b/i, 'promises a result'],
];
export function checkPrompt(text) {
  const t = String(text ?? '');
  for (const [re, reason] of ASK) if (re.test(t)) return { blocked: true, reason };
  return { blocked: false };
}
export function checkOutput(text) {
  const t = String(text ?? '');
  for (const [re, reason] of SAY) if (re.test(t)) return { blocked: true, reason };
  return { blocked: false };
}

// ---------- compliance log ----------
const userRef = id => crypto.createHmac('sha256', process.env.ENCRYPTION_KEY || 'dev-only').update('ai-log:' + id).digest('hex').slice(0, 24);
// Redacted for the log: e-mails, phones, keys (aiaccess.redact), then money amounts and long numbers.
export const scrub = s => redact(String(s ?? '').slice(0, 4000)).replace(/\+?\d[\d\s().-]{7,}\d/g, m => (m.replace(/\D/g, '').length >= 9 ? '[number]' : m)).replace(/[$€£]\s?\d[\d,]*(\.\d+)?/g, '$[amount]').replace(/\b\d{4,}(\.\d+)?\b/g, '[n]');
export async function logAi({ tool, userId, prompt, output, outcome, reason, model }) {
  await run('INSERT INTO ai_compliance_log (tool, user_ref, prompt, output, outcome, reason, model, at) VALUES (?,?,?,?,?,?,?,?)',
    tool, userRef(userId), scrub(prompt), scrub(output), outcome, reason || null, model || null, now()).catch(() => {});
}
export async function readLog({ limit = 100, tool } = {}) {
  const keep = Math.max(30, Math.min(3650, +process.env.AI_LOG_RETENTION_DAYS || 1095));
  await run('DELETE FROM ai_compliance_log WHERE at < ?', now() - keep * 864e5).catch(() => {});
  return all(`SELECT id, tool, user_ref, prompt, output, outcome, reason, model, at FROM ai_compliance_log ${tool ? 'WHERE tool = ?' : ''} ORDER BY id DESC LIMIT ?`, ...(tool ? [tool, limit] : [limit]));
}

// ---------- the pipeline ----------
// ai({ system, user }) -> { text, model } | null when no AI is available; fallback() -> text from rules.
export async function runGuarded({ tool, userId, question = '', facts, sources, ai, fallback, count = () => {} }) {
  const started = Date.now();
  const done = async (outcome, body, reason, model) => {
    count('ai_tool', `${tool}:${outcome}`);
    const ms = Date.now() - started; count('ai_latency', `${tool}:${ms < 1000 ? '<1s' : ms < 3000 ? '1-3s' : ms < 10000 ? '3-10s' : '>10s'}`);
    await logAi({ tool, userId, prompt: question, output: body.explanation, outcome, reason, model });
    return { tool, outcome, ...body, facts, sources, aiGenerated: outcome === 'ai', disclaimer: outcome === 'ai' ? DISCLAIMER : RULES_DISCLAIMER, ...(reason ? { blockedReason: reason } : {}) };
  };
  if (killed(tool)) { count('ai_tool', `${tool}:killed`); throw Object.assign(new Error('This tool is switched off for now.'), { status: 503, code: 'killed' }); }
  const p = checkPrompt(question);
  if (p.blocked) return done('blocked_prompt', { explanation: REFUSAL, keyPoints: [] }, p.reason);
  let out = null;
  try { out = await ai(); } catch { out = null; }
  if (out?.text) {
    const o = checkOutput(`${out.text}\n${(out.keyPoints || []).join('\n')}`);
    if (o.blocked) return done('blocked_output', { explanation: `${REFUSAL} The facts below were calculated from your data.`, keyPoints: [] }, o.reason, out.model);
    return done('ai', { explanation: out.text, keyPoints: out.keyPoints || [] }, null, out.model);
  }
  const fb = fallback();
  const o = checkOutput(`${fb.text}\n${(fb.keyPoints || []).join('\n')}`); // the rules are checked too
  if (o.blocked) return done('blocked_output', { explanation: REFUSAL, keyPoints: [] }, o.reason, 'rules');
  return done('rules', { explanation: fb.text, keyPoints: fb.keyPoints || [] }, null, 'rules');
}
